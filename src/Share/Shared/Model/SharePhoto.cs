using Plugin.FacebookKit.Share.Controls;

namespace Plugin.FacebookKit.Share;

/// <summary>
/// A photo for <see cref="ISharing"/>.
/// </summary>
public class SharePhoto : IShareMedia
{
    /// <summary>
    /// Gets or sets the image data.
    /// </summary>
    /// <remarks>
    /// Use this property when the image is available as in-memory data.
    /// </remarks>
    public byte[]? ImageData { get; set; }

    /// <summary>
    /// A URI reference of the image to share. Do not use to set <see cref="ISharingContent"/> 
    /// of either <see cref="ShareButton"/> or <see cref="SendButton"/>.
    /// </summary>
    /// <remarks>
    /// This property is used when the photo is referenced by a local or remote URI
    /// instead of an in-memory image.
    /// </remarks>
    public Uri? ImageUri { get; set; }

    /// <summary>
    /// Specifies whether the photo represented by the receiver was generated by the user (<code>true</code>)
    /// or by the application (<code>false</code>). 
    /// </summary>
    /// <remarks>
    /// Some Facebook sharing features require this value to indicate whether the
    /// content originated from the user.
    /// </remarks>
    public bool IsUserGenerated { get; set; }

    /// <summary>
    /// Gets or sets an optional caption for the photo.
    /// </summary>
    public string? Caption { get; set; }

    /// <summary>
    /// Convenience method to build a new photo object with an imageURL.
    /// This method should only be used when adding photo content to open graph stories.
    /// For example, if you’re trying to share a photo from the web by itself, download the image and use
    /// <code>init(image:isUserGenerated:)</code> instead.
    /// </summary>
    /// <param name="imageData">If the photo is resident in memory, this method supplies the data </param>
    /// <param name="isUserGenerated">
    /// <see langword="true"/> if the image was generated by the user; otherwise, <see langword="false"/>.
    /// </param>
    public SharePhoto(byte[] imageData, bool isUserGenerated)
    {
        ImageData = imageData;
        IsUserGenerated = isUserGenerated;
    }

    /// <summary>
    /// Convenience method to build a new photo object with an imageURL.
    /// This method should only be used when adding photo content to open graph stories.
    /// For example, if you’re trying to share a photo from the web by itself, download the image and use
    /// <code>init(image:isUserGenerated:)</code> instead.
    /// </summary>
    /// <param name="imageUri">The URI of the image to share.</param>
    /// <param name="isUserGenerated">
    /// <see langword="true"/> if the image was generated by the user; otherwise, <see langword="false"/>.
    /// </param>
    [Obsolete("SharePhoto only supports direct image generation. Use the byte[] constructor instead.", false)]
    public SharePhoto(Uri imageUri, bool isUserGenerated)
    {
        ImageUri = imageUri;
        IsUserGenerated = isUserGenerated;
    }
    
    /// <summary>
    /// Returns the string representation of the object.
    /// </summary>
    /// <returns></returns>
    public string DebugDescription() => $"ShareVideo ImageData={string.Join(", ", ImageData?.ToString())}, ImageUri={ImageUri?.AbsoluteUri}, IsUserGenerated={IsUserGenerated}" +
        $"Caption={Caption}";
}